// Helper functions
export const getProductBySlug = (slug: string): Product | undefined => {
  return products.find(p => p.slug === slug);
};

export const getProductById = (id: string): Product | undefined => {
  return products.find(p => p.id === id);
};

export const getProductsByCategory = (category: string): Product[] => {
  return products.filter(p => p.category === category);
};

export const getFeaturedProducts = (): Product[] => {
  return products.filter(p => p.featured);
};

export const getNewArrivals = (): Product[] => {
  return products.filter(p => p.newArrival);
};

export const getBestSellers = (): Product[] => {
  return products.filter(p => p.bestSeller);
};

export const searchProducts = (query: string): Product[] => {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  return products.filter(p => 
    p.name.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q) ||
    p.description.toLowerCase().includes(q) ||
    p.shortDescription.toLowerCase().includes(q) ||
    p.tags.some(t => t.toLowerCase().includes(q)) ||
    p.material.toLowerCase().includes(q)
  );
};

export const getAllSizes = (): string[] => {
  const sizes = new Set<string>();
  products.forEach(p => p.sizes.forEach(s => sizes.add(s)));
  return ['S', 'M', 'L', 'XL', 'XXL'].filter(s => sizes.has(s));
};

export const getAllColors = (): { name: string; hex: string }[] => {
  const colorMap = new Map<string, string>();
  products.forEach(p => p.colors.forEach(c => colorMap.set(c.name, c.hex)));
  return Array.from(colorMap.entries()).map(([name, hex]) => ({ name, hex }));
};

export const getPriceRange = (): [number, number] => {
  const prices = products.map(p => p.price);
  return [Math.min(...prices), Math.max(...prices)];
};

